"""
StudyTrade — Strategy Base Engine and Signal Abstractions
===========================================================

Defines the plug-in architecture for systematic option buying strategies.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum

import pandas as pd


class SignalDirection(StrEnum):
    BUY_CALL = "BUY_CALL"
    BUY_PUT = "BUY_PUT"
    BULL_CALL_SPREAD = "BULL_CALL_SPREAD"
    BEAR_PUT_SPREAD = "BEAR_PUT_SPREAD"
    CLOSE = "CLOSE"
    HOLD = "HOLD"


@dataclass(frozen=True)
class TradeSignal:
    """Standard signal generated by a strategy."""

    timestamp: datetime
    underlying_symbol: str
    direction: SignalDirection
    strength: float  # Confidence score between 0.0 and 1.0
    reason: str
    target_delta: float = 0.40  # Desired Delta for option contract selection
    min_dte: int = 5
    max_dte: int = 30


class BaseStrategy(ABC):
    """
    Abstract strategy base class. Every strategy implements `generate_signals`.
    """

    def __init__(self, name: str) -> None:
        self.name = name

    @abstractmethod
    def generate_signals(
        self,
        spot_df: pd.DataFrame,
        chain_df: pd.DataFrame | None = None,
    ) -> list[TradeSignal]:
        """
        Analyze price time-series and generate trade signals.

        Parameters
        ----------
        spot_df : pd.DataFrame
            Underlying OHLCV DataFrame up to decision point (no lookahead).
        chain_df : pd.DataFrame, optional
            Current option chain snapshot.

        Returns
        -------
        list of TradeSignal
        """
        pass
